"""Load, validate and refresh the open-source research corpus.

Metadata (license, activity) comes from the GitHub API through the ``gh`` CLI
and is stored in research/metadata.json. Nothing here claims hardware
verification: every project is unverified for the A810 Lite unless evidence
says otherwise.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "research" / "corpus.toml"
METADATA = ROOT / "research" / "metadata.json"
CATEGORIES = frozenset(
    {
        "headunit",
        "pi",
        "esp32",
        "can",
        "media",
        "integration",
        "reveng",
        "test",
        "quality",
        "api",
        "dashcam",
    }
)
# Licenses whose code must not be copied into this MIT project.
COPYLEFT = ("GPL", "AGPL", "LGPL")


def load_corpus(path: Path = CORPUS) -> list[dict]:
    with path.open("rb") as handle:
        projects = tomllib.load(handle).get("project", [])
    slugs = [p["slug"] for p in projects]
    if len(slugs) != len(set(slugs)):
        raise ValueError("duplicate slug in corpus")
    for project in projects:
        missing = {"slug", "category", "role", "kenpi_use"} - project.keys()
        if missing:
            raise ValueError(f"{project.get('slug')}: missing {sorted(missing)}")
        if project["category"] not in CATEGORIES:
            raise ValueError(f"{project['slug']}: unknown category")
    return projects


def load_metadata(path: Path = METADATA) -> dict[str, dict]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def reuse_policy(license_id: str | None) -> str:
    if not license_id or license_id in ("NOASSERTION", "none"):
        return "reference-only (license unclear)"
    if any(tag in license_id for tag in COPYLEFT):
        return "reference-only (copyleft)"
    return "may-depend (permissive; confirm per component)"


def fetch(slug: str) -> dict:
    result = subprocess.run(
        [
            "gh",
            "api",
            f"repos/{slug}",
            "--jq",
            "{license: (.license.spdx_id // null), pushed: .pushed_at[:10],"
            " archived: .archived, language: .language}",
        ],
        capture_output=True,
        text=True,
        timeout=60,
    )
    if result.returncode != 0:
        return {"error": result.stderr.strip()[:200]}
    return json.loads(result.stdout)


def refresh() -> int:
    metadata = {}
    for project in load_corpus():
        metadata[project["slug"]] = fetch(project["slug"])
    METADATA.write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return len(metadata)


def render_markdown(projects: list[dict], metadata: dict[str, dict]) -> str:
    lines = [
        "# Open-source research corpus",
        "",
        "Generated by `python -m kenpi.tools.research_corpus render` from",
        "`research/corpus.toml` and `research/metadata.json`. No project listed here is",
        "verified on A810 Lite, Kenwood DMX5710S, Pi 5 or ESP32-S3 hardware by Kenpi.",
        "Copyleft or unclear-license projects are reference-only: do not copy their code.",
        "",
    ]
    for category in sorted({p["category"] for p in projects}):
        lines += [
            f"## {category}",
            "",
            "| Project | License | Last push | Reuse policy | Role / Kenpi use |",
            "|---|---|---|---|---|",
        ]
        for p in sorted(projects, key=lambda item: item["slug"]):
            if p["category"] != category:
                continue
            meta = metadata.get(p["slug"], {})
            license_id = meta.get("license")
            pushed = meta.get("pushed", "unknown")
            if meta.get("archived"):
                pushed += " (archived)"
            lines.append(
                f"| [{p['slug']}](https://github.com/{p['slug']}) | {license_id or 'none/unknown'}"
                f" | {pushed} | {reuse_policy(license_id)} | {p['role']}: {p['kenpi_use']} |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    command = argv[0] if argv else "render"
    if command == "refresh":
        print(f"refreshed {refresh()} projects")
    elif command == "render":
        out = ROOT / "docs" / "research-corpus.md"
        out.write_text(
            render_markdown(load_corpus(), load_metadata()), encoding="utf-8"
        )
        print(f"wrote {out}")
    else:
        print("usage: research_corpus [refresh|render]", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
