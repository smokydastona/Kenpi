"""WireGuard remote-access policy and configuration (ADR 0003).

Remote access is off by default and is a network boundary only; the gateway still
requires a valid per-device credential. The server private key never appears in the
rendered config (it is loaded from a 0600 file by ``PostUp``) and is never backed up.
Not validated against a live tunnel in this repository's CI.
"""

from __future__ import annotations

import base64
import ipaddress
import json
import os
import re
import subprocess
import time
from collections.abc import Callable, Sequence
from pathlib import Path

from kenpi.security.devices import DeviceRegistry

INTERFACE = "wg-kenpi"
_KEY = re.compile(r"^[A-Za-z0-9+/]{43}=$")


def valid_wireguard_key(value: str) -> bool:
    if not _KEY.match(value):
        return False
    try:
        return len(base64.b64decode(value, validate=True)) == 32
    except ValueError:
        return False


class RemoteState:
    """Persistent enable flag, re-read on every check so the CLI takes effect immediately."""

    def __init__(self, state_dir: str | Path) -> None:
        self._dir = Path(state_dir)
        self._file = self._dir / "remote.json"

    def enabled(self) -> bool:
        try:
            return json.loads(self._file.read_text()).get("enabled") is True
        except (OSError, ValueError):
            return False

    def set(self, enabled: bool) -> None:
        self._dir.mkdir(mode=0o700, parents=True, exist_ok=True)
        tmp = self._file.with_suffix(".tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as handle:
            json.dump({"enabled": enabled, "changed_at": time.time()}, handle)
        os.replace(tmp, self._file)


def ensure_server_key(path: str | Path) -> str:
    """Create (once, mode 0600) the server key; returns its public key."""
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey

    path = Path(path)
    if not path.exists():
        path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        key = X25519PrivateKey.generate()
        raw = key.private_bytes(
            serialization.Encoding.Raw,
            serialization.PrivateFormat.Raw,
            serialization.NoEncryption(),
        )
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as handle:
            handle.write(base64.b64encode(raw).decode() + "\n")
    raw = base64.b64decode(path.read_text().strip())
    public = (
        X25519PrivateKey.from_private_bytes(raw)
        .public_key()
        .public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    )
    return base64.b64encode(public).decode()


def render_config(
    network: str, listen_port: int, private_key_path: str | Path,
    peers: dict[str, tuple[str, str]],
) -> str:  # fmt: skip
    net = ipaddress.ip_network(network)
    if not net.is_private or net.version != 4 or net.prefixlen > 29:
        raise ValueError(
            "WireGuard network must be a private IPv4 range of at least 6 hosts"
        )
    if not 1 <= listen_port <= 65535:
        raise ValueError("invalid WireGuard listen port")
    gateway = next(net.hosts())
    lines = [
        "# Generated by kenpi; do not edit. Contains no private key.",
        "[Interface]",
        f"Address = {gateway}/{net.prefixlen}",
        f"ListenPort = {listen_port}",
        f"PostUp = wg set %i private-key {private_key_path}",
    ]
    for device_id in sorted(peers):
        key, address = peers[device_id]
        if not valid_wireguard_key(key) or ipaddress.ip_address(address) not in net:
            raise ValueError(f"invalid peer for device {device_id}")
        lines += ["", f"# device {device_id}", "[Peer]", f"PublicKey = {key}",
                  f"AllowedIPs = {address}/32"]  # fmt: skip
    return "\n".join(lines) + "\n"


Runner = Callable[[Sequence[str]], int]


def _run(command: Sequence[str]) -> int:
    return subprocess.run(command, check=False, timeout=30).returncode


class RemoteAccess:
    def __init__(
        self,
        registry: DeviceRegistry,
        state: RemoteState,
        network: str,
        listen_port: int,
        key_path: str | Path,
        conf_path: str | Path = f"/etc/wireguard/{INTERFACE}.conf",
        runner: Runner = _run,
    ) -> None:
        self._registry, self._state, self._network = registry, state, network
        self._port, self._key, self._conf, self._run = (
            listen_port,
            key_path,
            Path(conf_path),
            runner,
        )

    def write_config(self) -> str:
        ensure_server_key(self._key)
        text = render_config(
            self._network,
            self._port,
            self._key,
            self._registry.wireguard_peers(self._network),
        )
        tmp = self._conf.with_suffix(".tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
        os.replace(tmp, self._conf)
        return text

    def enable(self) -> None:
        self._state.set(True)
        self._registry.audit("remote_enabled")
        self.apply()

    def disable(self) -> None:
        self._state.set(False)
        self._registry.audit("remote_disabled")
        self.apply()

    def apply(self) -> None:
        """Bring the tunnel in line with the flag and the current (non-revoked) peers."""
        if not self._state.enabled():
            self._run(["wg-quick", "down", INTERFACE])
            return
        self.write_config()
        if self._run(["wg", "show", INTERFACE]) != 0:
            if self._run(["wg-quick", "up", INTERFACE]) != 0:
                raise RuntimeError("wg-quick up failed")
            return
        stripped = self._conf.with_suffix(".stripped")
        fd = os.open(stripped, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        os.close(fd)
        try:
            if (
                self._run(["sh", "-c", f"wg-quick strip {self._conf} > {stripped}"])
                != 0
            ):
                raise RuntimeError("wg-quick strip failed")
            if self._run(["wg", "syncconf", INTERFACE, str(stripped)]) != 0:
                raise RuntimeError("wg syncconf failed")
        finally:
            stripped.unlink(missing_ok=True)
